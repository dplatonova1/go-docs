import {
  formatChecklistLabel,
  parseChecklistText,
} from '../parseChecklistText';

describe('formatChecklistLabel', () => {
  it.each([
    ['паспорт', 'Паспорт'],
    ['копия паспорта;', 'Копия паспорта'],
    ['фото 3×4,', 'Фото 3×4'],
    ['справка о несудимости , ; ', 'Справка о несудимости'],
    ['  выписка со счёта  ', 'Выписка со счёта'],
    ['паспорт, копия всех страниц;', 'Паспорт, копия всех страниц'],
    ['паспорт РФ', 'Паспорт РФ'],
    ['«копия» паспорта', '«Копия» паспорта'],
    ['(оригинал) диплома', '(Оригинал) диплома'],
    ['љична карта', 'Љична карта'],
    ['đačka knjižica;', 'Đačka knjižica'],
    ['и т. д.', 'И т. д.'],
  ])('«%s» → «%s»', (input, expected) => {
    expect(formatChecklistLabel(input)).toBe(expected);
  });

  it.each([
    // Точкой заканчиваются сокращения, двоеточие выдаёт заголовок.
    'Выписка из банка.',
    'Потребна документација:',
    // Первое слово с цифры — регистр не трогаем.
    '2 фотографии',
    '3x4 фото',
  ])('не меняет «%s»', label => {
    expect(formatChecklistLabel(label)).toBe(label);
  });

  it('строка из одних разделителей становится пустой', () => {
    expect(formatChecklistLabel(' , ; ')).toBe('');
  });

  it('идемпотентна', () => {
    const once = formatChecklistLabel('  «копия» паспорта; ');
    expect(formatChecklistLabel(once)).toBe(once);
  });
});

describe('parseChecklistText', () => {
  it('одна непустая строка — один пункт', () => {
    expect(parseChecklistText('Паспорт\nФотография\nСправка')).toEqual([
      'Паспорт',
      'Фотография',
      'Справка',
    ]);
  });

  it('пропускает пустые строки и строки из одних пробелов', () => {
    expect(parseChecklistText('\n\nПаспорт\n   \n\t\nФото\n\n')).toEqual([
      'Паспорт',
      'Фото',
    ]);
  });

  it('обрезает пробелы по краям, включая неразрывный', () => {
    expect(parseChecklistText('  Паспорт \n\tФото ')).toEqual([
      'Паспорт',
      'Фото',
    ]);
  });

  it('понимает любые переводы строк', () => {
    expect(parseChecklistText('А\r\nБ\rВ\u2028Г\u2029Д')).toEqual([
      'А',
      'Б',
      'В',
      'Г',
      'Д',
    ]);
  });

  it.each([
    ['1. Паспорт', 'Паспорт'],
    ['12) Паспорт', 'Паспорт'],
    ['1.2. Паспорт', 'Паспорт'],
    ['1.\tПаспорт', 'Паспорт'],
    ['1.Паспорт', 'Паспорт'],
    ['- Паспорт', 'Паспорт'],
    ['– Паспорт', 'Паспорт'],
    ['— Паспорт', 'Паспорт'],
    ['• Паспорт', 'Паспорт'],
    ['● Паспорт', 'Паспорт'],
    ['▪ Паспорт', 'Паспорт'],
    ['◦ Паспорт', 'Паспорт'],
    ['· Паспорт', 'Паспорт'],
    ['* Паспорт', 'Паспорт'],
    ['   •   Паспорт', 'Паспорт'],
  ])('убирает маркер: «%s»', (line, expected) => {
    expect(parseChecklistText(line)).toEqual([expected]);
  });

  it.each([
    '2024 год рождения',
    '3.5 кг багажа',
    'Фото 3.5×4.5 см',
    'Выписка — за 6 месяцев',
    // Осознанный пропуск, см. комментарий к LIST_MARKER.
    '1.2 Паспорт',
  ])('не трогает текст, похожий на маркер: «%s»', line => {
    expect(parseChecklistText(line)).toEqual([line]);
  });

  it('убирает только один маркер', () => {
    expect(parseChecklistText('1. - Паспорт')).toEqual(['- Паспорт']);
  });

  it('строка из одного маркера пунктом не становится', () => {
    expect(parseChecklistText('-\n1.\n•\nПаспорт')).toEqual(['Паспорт']);
  });

  it('оформляет пункты после снятия маркера', () => {
    expect(parseChecklistText('1. копия паспорта;\n- фото 3×4,\n;')).toEqual([
      'Копия паспорта',
      'Фото 3×4',
    ]);
  });

  it('пустой текст — пустой список', () => {
    expect(parseChecklistText('')).toEqual([]);
    expect(parseChecklistText(' \n \n')).toEqual([]);
  });

  it('реальный список с сайта ведомства', () => {
    const pasted = [
      'Потребна документација:',
      '',
      '1. Попуњен захтев за издавање дозволе за привремени боравак;',
      '2.\tВажећа путна исправа (фотокопија);',
      '  • Доказ о обезбеђеном смештају ',
      '',
      '- Доказ о средствима за издржавање',
    ].join('\r\n');

    expect(parseChecklistText(pasted)).toEqual([
      'Потребна документација:',
      'Попуњен захтев за издавање дозволе за привремени боравак',
      'Важећа путна исправа (фотокопија)',
      'Доказ о обезбеђеном смештају',
      'Доказ о средствима за издржавање',
    ]);
  });
});
