/**
 * Разбор вставленного текста на пункты чек-листа.
 *
 * Эвристика намеренно простая и детерминированная — никакого ML/NLP
 * (ADR-0004): одна непустая строка — один пункт. Результат не
 * сохраняется сразу, а показывается пользователю редактируемым списком,
 * поэтому ошибки эвристики исправляются руками, а не усложнением правил.
 *
 * Правила для каждой строки:
 * 1. обрезать пробельные символы по краям (включая неразрывный пробел,
 *    который часто приходит при копировании с сайтов);
 * 2. убрать один маркер списка в начале строки;
 * 3. оформить текст пункта — см. `formatChecklistLabel`;
 * 4. пропустить строку, если после этого она пустая.
 */

/**
 * Маркер списка в начале строки.
 *
 * - `1.` `12)` `1.2.` — нумерация с точкой или скобкой. `(?!\d)` не даёт
 *   принять за маркер начало дробного числа: в «3.5 кг» маркера нет.
 * - `-` `–` `—` `•` `●` `▪` `◦` `·` `*` — маркеры маркированных списков.
 *
 * Многоуровневая нумерация без финальной точки («1.2 Паспорт») маркером
 * не считается сознательно: её не отличить от числа в начале строки
 * («3.5 кг»). Лишний номер пользователь уберёт в предпросмотре, а
 * срезанное число из текста требования он может и не заметить.
 *
 * Пробелы после маркера тоже снимаются: при копировании между маркером и
 * текстом часто остаётся табуляция.
 */
const LIST_MARKER = /^(?:\d+(?:\.\d+)*[.)](?!\d)|[-–—•●▪◦·*])\s*/u;

/**
 * Разделители строк: Windows (`\r\n`), старый macOS (`\r`), Unix (`\n`)
 * и юникодные разделители строки и абзаца — последние встречаются в
 * тексте, скопированном из PDF.
 */
const LINE_BREAK = /\r\n|[\r\n\u2028\u2029]/u;

/**
 * Хвост пункта, оставшийся от перечисления: пробелы, запятые, точки с
 * запятой — «Паспорт;», «Фото 3×4, ».
 *
 * Точка и двоеточие не снимаются: точкой заканчиваются сокращения
 * («и т. д.», «г.»), а двоеточие у заголовка раздела подсказывает
 * пользователю, что это не документ и строку стоит удалить.
 */
const TRAILING_SEPARATORS = /[\s,;]+$/u;

/**
 * Первая буква первого слова. Перед ней допускаются только знаки
 * препинания — кавычки и скобки: «(оригинал) диплома» → «(Оригинал)
 * диплома». Если слово начинается с цифры («2 фотографии», «3x4 фото»),
 * регистр не меняется: иначе вышло бы «3X4».
 */
const FIRST_LETTER = /^(\p{P}*)(\p{Ll})/u;

/**
 * Оформление текста пункта: без пробелов по краям, без хвостовых
 * разделителей, первое слово с большой буквы. Остальной текст не
 * меняется — «паспорт РФ» становится «Паспорт РФ», а не «Паспорт рф».
 *
 * Функция идемпотентна: повторное применение ничего не меняет, поэтому её
 * безопасно вызывать и при разборе, и при правке, и при сохранении.
 */
export function formatChecklistLabel(label: string): string {
  return label
    .trim()
    .replace(TRAILING_SEPARATORS, '')
    .replace(
      FIRST_LETTER,
      (_match, prefix: string, letter: string) => prefix + letter.toUpperCase(),
    );
}

export function parseChecklistText(text: string): string[] {
  return text
    .split(LINE_BREAK)
    .map(line => formatChecklistLabel(line.trim().replace(LIST_MARKER, '')))
    .filter(line => line.length > 0);
}
