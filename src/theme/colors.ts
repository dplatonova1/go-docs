/**
 * Цвета интерфейса для светлой и тёмной системной темы.
 *
 * Без явного цвета текст React Native на Android рисуется чёрным при любой
 * теме, а фон окна в тёмной теме тёмно-серый. Вместе это чёрный текст на
 * тёмном фоне — экран выглядит пустым. Поэтому фон, текст и рамки каждый
 * компонент берёт отсюда, а не полагается на умолчания платформы.
 *
 * Контраст — требование доступности, а не вкус: текст держит не меньше
 * 7:1 к фону экрана и карточки (WCAG AAA), рамки элементов управления — не
 * меньше 3:1 (WCAG 1.4.11). Это проверяет тест в
 * `__tests__/colors.test.ts`, так что при подборе палитры незаметно
 * просадить контраст не выйдет.
 *
 * Палитра взята из темы tweakcn и адаптирована: цвета, не прошедшие пороги,
 * сдвинуты по светлоте с сохранением оттенка. У каждого изменённого цвета
 * в комментарии — исходное значение из темы; при обновлении темы сверяться
 * с ним. Не перенесены `sidebar-*`, `chart-*`, `popover`, `muted`,
 * `accent`, `input`, `ring`: для них в приложении нет элементов.
 */

import { useColorScheme } from 'react-native';

export type ThemeColors = {
  /** Фон экрана. */
  readonly background: string;
  /**
   * Фон карточек поверх экрана. Полупрозрачный в обеих темах, поэтому
   * кладётся только поверх `background` — шапка, нижняя панель и
   * карточки так и лежат. Контраст тест считает по цвету, наложенному
   * на `background`.
   */
  readonly surface: string;
  /**
   * `surface`, уже наложенный на `background`, — непрозрачный. Для
   * нативных элементов, которые не должны просвечивать: у шапки стека
   * Android сквозь полупрозрачный фон проступала её же тень — полосой в
   * несколько пикселей (найдено 2026-10-03). Совпадение с наложением
   * проверяет тест.
   */
  readonly surfaceOpaque: string;
  /** Основной текст. */
  readonly text: string;
  /** Второстепенный текст: пояснения, плейсхолдеры. */
  readonly textSecondary: string;
  /** Фон основной кнопки. */
  readonly primary: string;
  /** Текст на `primary`. */
  readonly onPrimary: string;
  /**
   * Акцент без заливки: активная вкладка (иконка и подпись), спиннеры,
   * рамка выбранного варианта. Оттенок `primary`, но контрастный к фону:
   * заливку кнопки видно по надписи на ней, а эти элементы — только по
   * их собственному цвету. Раз им красится подпись, держит 7:1, как
   * текст.
   */
  readonly indicator: string;
  /**
   * Рамки полей ввода и кнопок-контуров — там, где рамка показывает
   * границу элемента. Не меньше 3:1 к фону.
   */
  readonly border: string;
  /**
   * Разделители (у карточек свой кант, см. `card.ts`). Декоративный
   * цвет, контраст не нормирован — не использовать как единственную
   * границу элемента управления, для этого `border`.
   */
  readonly divider: string;
  /**
   * Плашка «Прикреплено» — еле заметный полупрозрачный голубой (решено
   * 2026-10-02). Текст на ней — `text`: контраст проверяет тест по цвету,
   * наложенному на карточку.
   */
  readonly attachedSurface: string;
  /** Рамка плашки «Прикреплено» — тот же голубой, чуть плотнее. */
  readonly attachedBorder: string;
  /**
   * Текст ошибок. Цвет — не единственный признак ошибки: рядом всегда
   * есть текст, иначе её не различат люди с нарушением цветовосприятия.
   */
  readonly danger: string;
};

