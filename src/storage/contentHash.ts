/**
 * Отпечаток содержимого файла — SHA-256 от незашифрованных байтов.
 *
 * Считается ровно один раз, по тем же байтам, которые уже прочитаны для
 * шифрования: второй раз файл не читается и не расшифровывается.
 *
 * Почему по открытому тексту, а не по шифротексту: у каждого шифрования
 * свой nonce (см. `crypto.ts`), и один и тот же файл каждый раз даёт
 * разные зашифрованные байты — сравнивать их бессмысленно.
 *
 * Хэш хранится в `documents.content_hash` и нужен только для того, чтобы
 * узнать уже загруженный файл. Это не секрет и не аутентификатор:
 * целостность проверяет AES-GCM при расшифровке.
 */

import { sha256 } from '@noble/hashes/sha2.js';
import { bytesToHex } from '@noble/hashes/utils.js';

export function contentHashOf(bytes: Uint8Array): string {
  return bytesToHex(sha256(bytes));
}
